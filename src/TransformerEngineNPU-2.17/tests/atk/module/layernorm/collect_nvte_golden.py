"""Collect NVTE LayerNorm split-guard goldens (offline twin of the bundle flow).

Run on a CUDA host with the pinned NVIDIA Transformer Engine importable as
``transformer_engine``. Input is a bundle-form case file generated by
``atk case`` with ``layernorm_forward.yaml`` / ``layernorm_backward.yaml``
(one run per phase file); output is the source-form case JSON, per-case
``input.bin`` (source args + shared FP32 statistics, bit-identical to the
online producer) and the NVTE outputs of the phase entry. See
``../_norm_split_collect.py`` for the layout and the offline/online parity
contract.

Example (forward; repeat with the backward file for the other phase)::

    NVIDIA_TF32_OVERRIDE=0 python collect_nvte_golden.py \\
        --cases result/layernorm/json/all_layernorm_forward.json \\
        --input-dir ./layernorm_inputs \\
        --golden-dir ./layernorm_goldens \\
        --cases-out ./layernorm_cases_offline
"""

import argparse
import sys
from pathlib import Path

_HERE = str(Path(__file__).resolve().parent)
_MODULE_ROOT = str(Path(_HERE).parent)
for _path in (_HERE, _MODULE_ROOT):
    if _path not in sys.path:
        sys.path.insert(0, _path)

import torch  # noqa: E402

import layernorm_inputs  # noqa: E402
from _norm_split_collect import collect_split_norm_goldens  # noqa: E402
from function_layernorm import run_layernorm_backward, run_layernorm_forward  # noqa: E402


def _parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--cases", required=True, help="bundle-form case JSON (forward or backward)"
    )
    parser.add_argument("--input-dir", required=True, help="canonical input artifact directory")
    parser.add_argument("--golden-dir", required=True, help="root used by the accuracy_load node")
    parser.add_argument(
        "--cases-out",
        default=None,
        help="directory for the source-form case JSON the NPU task consumes",
    )
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--backend-label", default="cpu_nvte")
    parser.add_argument(
        "--reject-import-token",
        default="TransformerEngineNPU",
        help="Fail if transformer_engine.__file__ contains this token; empty disables the check",
    )
    return parser.parse_args()


def main():
    args = _parse_args()
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required to collect NVTE golden outputs")
    collect_split_norm_goldens(
        args,
        inputs_module=layernorm_inputs,
        run_forward=run_layernorm_forward,
        run_backward=run_layernorm_backward,
        eps_position=4,
        manifest_prefix="layernorm",
    )


if __name__ == "__main__":
    main()
